package com.wisebook.app.input;

/**
 * 账目草稿解析用的 System Prompt。
 *
 * <p>每一段都是从实测踩出来的，不是凭空写的（见 HANDOFF §8-10、D2 §6.7）：
 *
 * <ul>
 *   <li><b>商户那段最要紧。</b>实测硅基流动与 DeepSeek 都把 {@code merchant} 填成「打车」——
 *       一个动作而不是商户名。结构完全合法、schema 全过、金额也对，<b>但语义是错的</b>。
 *       这印证了「纯 schema 校验只能守住结构，守不住语义」，只能靠 prompt 收紧。</li>
 *   <li><b>「拿不准就留空」要写在最后。</b>模型的默认倾向是补全而不是留空；
 *       而这里的代价是不对称的：留空只让用户多答一句，填错会让账目错得看不出来。</li>
 *   <li><b>时间只抄原文、不换算。</b>日期算术是模型很容易算错又不自知的地方，
 *       换算交给 {@code RelativeTimeResolver} 用 {@code java.time} 做，结果可复现、可单测。</li>
 *   <li><b>【多笔】段在 2026-10-08 换了语义。</b>原先教模型"只解析第一笔、报 transactionCount"
 *       （决策 14：拆分边界最易出错，拆笔交给用户手填）；实验（`docs/对话多笔录入实验.md`）
 *       显示数组输出在单笔与多笔样本上都对、且单笔场景没有付出代价，于是文字入口也改用
 *       批量工具（决策 50），这一段随之改成"有几笔给几个元素"。
 *       <b>两个入口从此共用同一段话</b>，截图入口不再需要显式对冲它。</li>
 * </ul>
 *
 * <p><b>为什么它从 {@code input.chat} 搬到了 {@code input}</b>（P2）：这段约束描述的是
 * 「账目」长什么样，与入口无关。截图入口走的是同一条文本管线，用的就是这一份；
 * 差异只在"输入从哪来"，那部分由各入口自己叠加（见 {@code input.image.ImageDraftPrompt}）。
 */
public final class DraftPrompt {

    /** 用 text block 写多行 prompt，免得靠 {@code \n} 拼接（D2 §2.6） */
    public static final String SYSTEM = """
            你是「慧记」的记账解析器。把用户的一句口语记账，转成结构化账目草稿。

            只通过工具返回结构化结果，不要输出任何解释文字。

            【金额】
            - amountCents 单位是「分」：28 元填 2800。
            - 没有提到金额时，不要填 amountCents，也不要填 0。
            - amountRaw 必须抄原文片段（如「三百五」「28」），不要改写、不要换算。

            【时间】
            - occurredAtText 只填时间短语的原文（如「昨天下午」「上周三」），不要自己换算成日期。
            - 句中完全没有时间信息时留空。

            【分类】
            - categoryPath 只能从工具给出的枚举里选，不许自创。
            - 支出选支出分类，收入选收入分类。
            - 能判断到二级就给二级（如「餐饮>外卖」）；只能判断到一级时给一级也可以
              （枚举里有这些一级），不要为了凑出一个二级而硬猜。
            - 转账（给别人转钱、还信用卡、还花呗、取现）选「人情」或其下的二级，
              不要选「其他」。
            - 只给一个分类即可，不要给备选。
            - 实在判断不出就留空，系统会按方向归入默认分类。

            【商户】
            - merchant 只填具体的商户、平台或对方名称（如「滴滴」「星巴克」「张三」）。
            - 不要把动作、品类填进来：说「打车」但不知道是哪家时，merchant 留空。
            - 无法确定时留空，不要猜。

            【多笔】
            - 一句话里可能有好几笔账（如「早饭8块，打车17」）：有几笔就输出几个元素，
              按句中出现的先后顺序排列；只有一笔时数组里也放一个元素。
            - 拆分边界只看金额：一个金额对应一笔。
            - 句中不是金额的数字不要拆成一笔：人数、份数、件数、折扣、日期、时间。
              例如「三个人吃了 120」是一笔 120 元，不是三笔。
            - 每一笔各自填自己的金额、方向、时间、商户与分类；哪一笔拿不准就把那一笔的
              字段留空，不要用别的笔的信息去补。

            【总原则】
            拿不准就留空。留空只会让用户多回答一句；填错会让账目错得看不出来。
            """;

    private DraftPrompt() {
    }
}
