package com.wisebook.app.input.image;

import com.wisebook.app.input.DraftPrompt;

/**
 * 截图入口的两段提示词。
 *
 * <p>它们<b>不是</b>另写一套解析规则：第二段直接以 {@link DraftPrompt#SYSTEM} 为底，
 * 只叠加"这是一张截图"这个信息。这样截图入口与文字入口对"账目长什么样"的理解
 * 始终是同一份（`docs/P2-截图实验.md` §4 选路线 B 的核心理由）。
 */
public final class ImageDraftPrompt {

    private ImageDraftPrompt() {
    }

    /**
     * 第一步：图 → 文字。
     *
     * <p>只有在「通用视觉模型」充当转写器时才会被用到——OCR 专用模型
     * （{@code DeepSeek-OCR}）不认 system 消息，只认它自己的固定模板
     * （见 {@code OpenAiCompatibleImageReader.OCR_TEMPLATE}）。
     *
     * <p>「逐条平铺、不要 Markdown 等级」这句是 P2 实验的直接产物：OCR 模型爱把账单
     * 渲染成 Markdown 层级（{@code #### 转账}），下游会把它读成"一份文档"而不是
     * "六条记录"，于是把 6 笔报成 1 笔。
     */
    public static final String TRANSCRIBE = """
            你是 OCR 文字识别器。逐字输出图片中所有可见文字，不要理解、不要总结、不要解释。

            要求：
            - 保留原始数字与符号，尤其是金额：小数点、正负号、货币符号都要照抄，不许改写或折算。
            - 逐条平铺：每一笔记录单独占一行或一个短段落。
            - 不要在行首加 # 之类的层级标题，不要用 Markdown 表格——下游要靠"一条记录一行"来数笔数。
            - 时间、商户名、支付方式、状态、订单号都照抄。
            - 只输出识别到的文字，不要输出「图片中显示」这类叙述。
            """;

    /**
     * 第二步：文字 → 账目（可能多笔）。
     *
     * <p>最后一段刻意与 {@link DraftPrompt#SYSTEM} 的【多笔】那一段<b>正面对冲</b>：
     * 文字入口是"只说第一笔、报出笔数"，截图入口是"每笔都要给一个元素"。
     * 两者语义相反，所以必须显式覆盖，不能指望模型自己分辨。
     */
    public static final String DRAFTS = DraftPrompt.SYSTEM + """

            【这是一张账单截图转成的文字，前面的规则按下面这几条调整】
            - 【多笔】那段不适用：这里是每一笔输出一个元素，按图中从上到下的顺序排列；
              只有一笔时数组里也放一个元素。不要只输出第一笔，也不要填 transactionCount。
            - 金额以文字里的数字为唯一依据：￥7.00 是 700 分，-15.00 表示支出 1500 分，
              +8.00 表示收入 800 分。不要靠"看起来像多少"估，必须逐位读准小数点与末尾的 0。
            - 符号决定方向：负数或不带符号的支出记 expense，正数/「收入」/「收转账」记 income，
              「转账 / 转给某人」记 transfer。
            - 时间是相对词（如「昨天 21:09」）时原样填进 occurredAtText，不要换算成日期。
            - merchant 只填收款方或商户名（如「星巴克」「张三」）；
              不要把「扫二维码付款」「使用建设银行储蓄卡支付」这类描述当成商户。
            - 截图里通常只有收款方名称，看不出买了什么。这时 categoryPath 留空，
              系统会归入该方向的默认分类——硬猜一个具体分类（把一个人名收款方
              猜成「购物>美妆」之类）会让它悄悄进报表，比留空糟得多。
            """;
}
