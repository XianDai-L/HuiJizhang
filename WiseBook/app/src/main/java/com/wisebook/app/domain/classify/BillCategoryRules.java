    private static final String MERCHANT_REASON_PREFIX = "按账单的商户名命中「";
    private static final String ITEM_REASON_PREFIX = "按账单的商品明细命中「";
    private static final String REASON_SUFFIX = "」";

    private BillCategoryRules() {
    }

    /** 命中结果：分类路径 + 给用户看的判据 */
    public static final class Hit {

        public final String path;
        public final String reason;

        Hit(String path, String reason) {
            this.path = path;
            this.reason = reason;
        }
    }

    /**
     * @param merchant 账单里的交易对方
     * @param items    账单里的商品明细（可空）
     * @return 命中返回路径与判据；没命中返回 {@code null}，由调用方兜底
     */
    public static Hit match(String merchant, List<String> items) {
        Hit byMerchant = matchOne(MERCHANT_RULES, merchant, MERCHANT_REASON_PREFIX);
        if (byMerchant != null) {
            return byMerchant;
        }
        if (items == null) {
            return null;
        }
        for (String item : items) {
            Hit byItem = matchOne(ITEM_RULES, item, ITEM_REASON_PREFIX);
            if (byItem != null) {
                return byItem;
            }
        }
        return null;
    }

    private static Hit matchOne(String[][] rules, String text, String reasonPrefix) {
        if (text == null) {
            return null;
        }
        // 复用去重键那套归一化（去空白 + 英文小写）：两处对"同一个商户"的判据必须一致，
        // 否则会出现"去重认为是两家、分类认为是同一家"这种自相矛盾
        String normalized = DedupeKey.normalizeMerchant(text);
        if (normalized.isEmpty()) {
            return null;
        }
        for (String[] rule : rules) {
            if (normalized.contains(rule[0])) {
                return new Hit(rule[1], reasonPrefix + rule[0] + REASON_SUFFIX);
            }
        }
        return null;
    }
